"""Prompts tiered manifest + browse-by-Set + drift check (Plan dx0u4s).

``aw prompts index [--check]`` regenerates ``.aw/records/prompts/INDEX.json`` (every prompt, all fields)
and a browse-by-``Set:`` human view (``INDEX.md``: each Set lists its members in ``Order``, Sets ordered
by most-recent activity, bounded to the 40 most-recent Sets, the rest available in the JSON).
``--check`` fails on drift (missing/stale generated views, name-metadata mismatches).

Consumes the shared core (`artifact_core`) and `artifact_naming`.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any, Dict, List, NamedTuple, Optional, Tuple

from agent_workflows import artifact_core as _core
from agent_workflows import artifact_meta as _am
from agent_workflows import artifact_naming as _naming

DEFAULT_INDEX_LIMIT = 40
INDEX_JSON = "INDEX.json"
INDEX_MD = "INDEX.md"
_MD_HEADER = "<!-- generated by `aw index prompts`; do not edit by hand -->"

_EXCLUDE_NAMES = {"INDEX.json", "INDEX.md", "README.md"}

# The legacy staged staging name: YYYYMMDD-HHMM-NN-<slug>.prompt.md
# The legacy staged name YYYYMMDD-HHMM-NN-<slug>.prompt.md is read by THE ONE file-name library.
_STAGED_NAME_RE = _naming._LEGACY_TIMESTAMP_RE


class PromptEntry(NamedTuple):
    """One indexed prompt (derived from its disposition dir, filename, and metadata comment)."""

    id6: Optional[str]
    path: str  # posix, relative to prompts_dir
    disposition: str  # pending/executed/superseded/not-executed/reusable
    date: str
    set_id: Optional[str]
    order: Optional[int]
    status: Optional[str]
    kind: Optional[str]
    slug: Optional[str] = None


def _parse_metadata_comment(text: str) -> Dict[str, str]:
    first = text.split("\n", 1)[0] if text else ""
    if not (
        first.startswith("<!--") and "aw-prompt:" in first and first.endswith("-->")
    ):
        return {}
    inner = first[4:-3].strip()
    if inner.startswith("aw-prompt:"):
        inner = inner[len("aw-prompt:") :].strip()
    if " . This HTML comment is" in inner:
        inner = inner.split(" . This HTML comment is", 1)[0].strip()
    elif " . " in inner:
        inner = inner.split(" . ", 1)[0].strip()
    meta = {}
    for part in inner.split("|"):
        part = part.strip()
        if ":" in part:
            k, v = part.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta


def _meta_context_for_prompts_dir(
    prompts_dir: Path,
) -> Tuple[Any, Path, Optional[Path]]:
    """Build an ``artifact_meta`` context covering ``prompts_dir``."""
    pdir = prompts_dir.resolve()
    repo_root: Optional[Path] = None
    for cand in (pdir, *pdir.parents):
        cparts = cand.parts
        if len(cparts) >= 4 and cparts[-3:] == (".aw", "records", "prompts"):
            repo_root = cand.parents[2]
            break
        if len(cparts) >= 3 and cparts[-2:] == (".agents", "prompts"):
            repo_root = cand.parents[1]
            break
    if repo_root is None:
        from agent_workflows import project_context as _proj_ctx

        repo_root = _proj_ctx.record_owner_root(pdir)
    if repo_root is not None:
        ctx = _am.legacy_context(repo_root)
        records_root = Path(ctx.logical_roots["records"])
        scan_repo = _am._scan_repo_root(ctx, records_root)
        if pdir.is_relative_to(records_root.resolve()) or (
            scan_repo is not None
            and pdir.is_relative_to((scan_repo / ".agents").resolve())
        ):
            return ctx, records_root, scan_repo
    prompts_ancestor: Optional[Path] = None
    for cand in (pdir, *pdir.parents):
        if cand.name == "prompts":
            prompts_ancestor = cand
            break
    if prompts_ancestor is not None:
        records_root = prompts_ancestor.parent
        state_root = (
            records_root.parent / "state"
            if records_root.name == "records"
            else records_root / ".aw-state"
        )
    else:
        records_root = pdir
        state_root = pdir / ".aw-state"
    ctx = type(
        "LegacyContext",
        (),
        {
            "logical_roots": {"records": str(records_root), "state": str(state_root)},
            "repo_root": repo_root or records_root,
        },
    )()
    return ctx, records_root, repo_root


def _cached_prompt_states(
    prompts_dir: Path, *, include_fields: bool = True
) -> Dict[Path, Any]:
    """Query ``artifact_meta.query(type='prompt')`` indexed by resolved path under ``prompts_dir``."""
    if not prompts_dir.is_dir():
        return {}
    pdir_res = prompts_dir.resolve()
    ctx, records_root, scan_repo = _meta_context_for_prompts_dir(pdir_res)
    with _am.scan_once(), _am.ephemeral_if_uninitialized():
        res = _am.query(
            type="prompt", project_context=ctx, include_fields=include_fields
        )
    by_path: Dict[Path, Any] = {}
    for st in res.rows:
        if not st.path:
            continue
        try:
            abs_p = _am.source_path(st.path, records_root, scan_repo).resolve()
        except Exception:
            continue
        if abs_p.is_relative_to(pdir_res):
            by_path[abs_p] = st
    return by_path


def _state_order(st: Any) -> Optional[int]:
    """Return non-negative integer Order from an ``artifact_meta.State``, or None."""
    fields = getattr(st, "fields", None)
    if isinstance(fields, dict):
        raw = fields.get("order")
        if isinstance(raw, int) and raw >= 0:
            return raw
        if isinstance(raw, str) and raw.strip().isdigit():
            return int(raw.strip())
    order_nn = getattr(st, "order_nn", None)
    if isinstance(order_nn, int) and order_nn >= 0:
        return order_nn
    return None


def _filename_slug(name: str) -> Optional[str]:
    """Extract the slug segment from a prompt filename."""
    m_leg = _STAGED_NAME_RE.match(name)
    if m_leg:
        return m_leg.group("slug")
    m_attr = _naming.parse_attributed(name)
    if m_attr:
        return m_attr.slug
    m_clust = _naming.parse_clustered(name)
    if m_clust:
        return m_clust.group("slug")
    return None


def _scan_prompts_with_states(
    prompts_dir: Path,
) -> Tuple[List[PromptEntry], List[_core.Drift], Dict[Path, Any]]:
    """Scan every prompt under ``prompts_dir`` via ``artifact_meta.query``."""
    entries: List[PromptEntry] = []
    drift: List[_core.Drift] = []
    if not prompts_dir.is_dir():
        return entries, drift, {}
    ignored_dirs = _core.get_ignored_dirs(prompts_dir)
    states = _cached_prompt_states(prompts_dir, include_fields=True)
    for p in sorted(prompts_dir.rglob("*.md")):
        if p.name in _EXCLUDE_NAMES or _core.is_ignored_path(
            p, prompts_dir, ignored_dirs
        ):
            continue
        rel = p.relative_to(prompts_dir).as_posix()
        disposition = rel.split("/", 1)[0]
        st = states.get(p.resolve())
        if st is None:
            st = _am.read_text(p.read_text(encoding="utf-8"), record_type="prompt")
            id6 = st.id6 if (st.id6 and _core.is_valid_id6(st.id6)) else None
            set_id = st.set_id or None
            order = _state_order(st)
            date = str(
                st.created_day
                or st.fields.get("created_day")
                or st.fields.get("created")
                or st.fields.get("date")
                or st.filename_date
                or ""
            )
            raw_kind = st.fields.get("prompt_kind") or st.fields.get("plan_role")
            kind = str(raw_kind) if raw_kind else None
            status = str(st.status) if st.status else disposition
            slug = (
                str(st.fields.get("slug"))
                if st.fields.get("slug")
                else _filename_slug(p.name)
            )
        else:
            id6 = None if st.id_derived else (st.id6 or None)
            set_id = st.set_id or None
            order = _state_order(st)
            date = str(
                st.created_day
                or st.fields.get("created_day")
                or (st.created_at[:10] if st.created_at else None)
                or st.filename_date
                or ""
            )
            raw_kind = st.fields.get("prompt_kind")
            kind = str(raw_kind) if raw_kind else None
            status = str(st.status) if st.status else disposition
            slug = _filename_slug(p.name)

        entries.append(
            PromptEntry(
                id6=id6,
                path=rel,
                disposition=disposition,
                date=date,
                set_id=set_id,
                order=order,
                status=status,
                kind=kind,
                slug=slug,
            )
        )
    return entries, drift, states


def scan_prompts(prompts_dir: Path) -> Tuple[List[PromptEntry], List[_core.Drift]]:
    """Scan every prompt under ``prompts_dir`` via ``artifact_meta.query``; return (entries, drift)."""
    entries, drift, _states = _scan_prompts_with_states(prompts_dir)
    return entries, drift


def build_index_json(entries: List[PromptEntry]) -> str:
    """Render the complete prompts manifest as deterministic JSON (sorted by path)."""
    payload = [e._asdict() for e in sorted(entries, key=lambda e: e.path)]
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def _set_last_touched(entries: List[PromptEntry]) -> Dict[str, str]:
    lt: Dict[str, str] = {}
    for e in entries:
        key = e.set_id or f"(singleton) {e.path}"
        if key not in lt or e.date > lt[key]:
            lt[key] = e.date
    return lt


def build_index_md(entries: List[PromptEntry], limit: int = DEFAULT_INDEX_LIMIT) -> str:
    """Render the browse-by-Set view: group by Set, members in Order, Sets by recent activity,
    bounded to the N most-recent Sets; Set-less prompts in a singleton band."""
    last_touched = _set_last_touched(entries)
    by_set: Dict[Optional[str], List[PromptEntry]] = {}
    for e in entries:
        by_set.setdefault(e.set_id, []).append(e)

    real_sets = [s for s in by_set if s is not None]

    def _inv_date(d: str) -> str:
        return "".join(str(9 - int(c)) if c.isdigit() else c for c in d) if d else ""

    ordered_sets = sorted(
        real_sets, key=lambda s: (_inv_date(last_touched.get(s, "")), s)
    )
    shown = ordered_sets[:limit]

    lines = [_MD_HEADER, "", "# Prompts by topic (Set)", ""]
    lines.append(
        f"Showing the {len(shown)} most-recent of {len(real_sets)} Sets; the full manifest is INDEX.json."
    )
    lines.append("")
    for s in shown:
        members = sorted(
            by_set[s], key=lambda e: (e.order if e.order is not None else 0, e.path)
        )
        lines.append(f"## {s}")
        lines.append("")
        for e in members:
            oid = f"{e.order:02d}" if e.order is not None else "--"
            pid = e.id6 or "??????"
            lines.append(f"- `{pid}` [{e.disposition}] {oid} {e.path}")
        lines.append("")
    singletons = by_set.get(None, [])
    if singletons:
        lines.append("## (singletons: no Set)")
        lines.append("")
        for e in sorted(singletons, key=lambda e: e.path):
            pid = e.id6 or "??????"
            lines.append(f"- `{pid}` [{e.disposition}] {e.path}")
        lines.append("")
    return "\n".join(lines)


def check_drift(
    repo_root: Path, prompts_dir: Path, limit: int = DEFAULT_INDEX_LIMIT
) -> List[_core.Drift]:
    entries, drift, states = _scan_prompts_with_states(prompts_dir)
    from agent_workflows import check_engine as _ce

    # Drift: name-vs-metadata mismatch on a clustered name (read via artifact_meta)
    for e in entries:
        base = Path(e.path).name
        m = _naming.parse_clustered(base)
        if not m or re.fullmatch(r"\d{4}", m.group("set")):
            continue
        st = states.get((prompts_dir / e.path).resolve())
        if st is None:
            continue
        meta_id = None if st.id_derived else (st.id6 or None)
        if meta_id and m.group("id6") != meta_id:
            drift.append(
                _core.Drift(
                    e.path,
                    "name-metadata-mismatch",
                    f"name id {m.group('id6')} != metadata Id {meta_id}",
                )
            )
        meta_set = (
            st.set_id
            if getattr(st, "created_at", None) is not None
            else getattr(st, "legacy_raw_set", None)
        )
        if meta_set and m.group("set") != meta_set:
            drift.append(
                _core.Drift(
                    e.path,
                    "name-metadata-mismatch",
                    f"name set {m.group('set')} != metadata Set {meta_set}",
                )
            )

    want_json = build_index_json(entries)
    want_md = build_index_md(entries, limit=limit)
    jp = prompts_dir / INDEX_JSON
    mp = prompts_dir / INDEX_MD

    for path_const, exists, matches, label in (
        (
            INDEX_JSON,
            jp.is_file(),
            jp.is_file() and jp.read_text(encoding="utf-8") == want_json,
            "INDEX.json",
        ),
        (
            INDEX_MD,
            mp.is_file(),
            mp.is_file() and mp.read_text(encoding="utf-8") == want_md,
            "INDEX.md",
        ),
    ):
        if not exists:
            drift.append(
                _ce.enrich_drift(
                    _core.Drift(
                        path_const,
                        "check.stale-index-missing",
                        f"{label} has not been generated; run 'aw index prompts'",
                    ),
                    recovery="aw index prompts",
                )
            )
        elif not matches:
            drift.append(
                _ce.enrich_drift(
                    _core.Drift(
                        path_const,
                        "check.stale-index-stale",
                        f"{label} is out of date; run 'aw index prompts'",
                    ),
                    recovery="aw index prompts",
                )
            )

    return drift


def _dirs(args: argparse.Namespace) -> Tuple[Path, Path]:
    from agent_workflows.project_context import resolve_verb_repo_root
    from agent_workflows import prompts as _prompts

    repo_root = resolve_verb_repo_root(getattr(args, "dir", None))
    prompts_dir = _prompts.prompts_root(repo_root)
    return repo_root, prompts_dir


def run_index(args: argparse.Namespace) -> int:
    repo_root, prompts_dir = _dirs(args)
    limit = getattr(args, "limit", None) or DEFAULT_INDEX_LIMIT
    if getattr(args, "check", False):
        drift = check_drift(repo_root, prompts_dir, limit=limit)
        # tsvagent Order 01 (n9ua3b) E-03: route all audiences through the shared renderer
        # via artifact_core.emit_index_check_result, preserving the legacy human lines byte-exact
        # via data["human_rendered"]. Rely on the renderer's return value (result.exit_code),
        # which identically preserves artifact_core.drift_exit_code(drift).
        return _core.emit_index_check_result(
            args,
            repo_root,
            drift,
            "prompts index --check: clean",
            command="index",
            target="prompts",
        )
    if not prompts_dir.is_dir():
        return _core.emit_index_missing_dir_refusal(
            args, repo_root, prompts_dir, target="prompts"
        )
    entries, drift = scan_prompts(prompts_dir)
    json_path = prompts_dir / INDEX_JSON
    md_path = prompts_dir / INDEX_MD
    new_json = build_index_json(entries)
    new_md = build_index_md(entries, limit=limit)

    json_existed = json_path.exists()
    md_existed = md_path.exists()
    json_changed = (not json_existed) or (
        json_path.read_text(encoding="utf-8") != new_json
    )
    md_changed = (not md_existed) or (md_path.read_text(encoding="utf-8") != new_md)

    if json_changed or md_changed:
        prompts_dir.mkdir(parents=True, exist_ok=True)
    if json_changed:
        json_path.write_text(new_json, encoding="utf-8")
    if md_changed:
        md_path.write_text(new_md, encoding="utf-8")

    from agent_workflows.result_types import select_output

    ctx = select_output(args)
    if (ctx.is_agent or ctx.is_json) and not getattr(args, "quiet", False):
        return _core.emit_index_write_result(
            args,
            repo_root,
            prompts_dir,
            target="prompts",
            noun="prompts",
            count=len(entries),
            json_changed=json_changed,
            md_changed=md_changed,
            json_existed=json_existed,
            md_existed=md_existed,
            drift=drift,
        )

    if drift and not getattr(args, "quiet", False):
        for d in drift:
            print(f"{d.location}: {d.rule}: {d.detail}")
    if not getattr(args, "quiet", False):
        # Outcome words, not lifecycle statuses: see the note in plans_index.run_index (9zvl2w E-01).
        # select_output is already imported above (before `ctx = select_output(args)`).
        from agent_workflows.term import Term

        try:
            _ctx = select_output(args)
            _color = _ctx.color
        except Exception:
            _color = None if not getattr(args, "no_color", False) else False
        term = Term(color=_color)
        try:
            rel_dir = prompts_dir.relative_to(repo_root).as_posix()
        except ValueError:
            rel_dir = prompts_dir.as_posix()
        dir_prefix = f"{rel_dir}/" if rel_dir and not rel_dir.endswith("/") else rel_dir
        dir_styled = term.color256(dir_prefix, 33)

        if not json_changed and not md_changed:
            status_lbl = term.status_256("up to date", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}, {INDEX_MD}"
            term.line(f"{status_lbl} {files_str} ({len(entries)} prompts)")
        elif json_changed and md_changed:
            status_lbl = term.status_256("wrote", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}, {INDEX_MD}"
            term.line(f"{status_lbl} {files_str} ({len(entries)} prompts)")
        elif md_changed:
            status_lbl = term.status_256("updated", width=12)
            files_str = f"{dir_styled}{INDEX_MD}"
            term.line(
                f"{status_lbl} {files_str} ({INDEX_JSON} up to date; {len(entries)} prompts)"
            )
        else:
            status_lbl = term.status_256("updated", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}"
            term.line(
                f"{status_lbl} {files_str} ({INDEX_MD} up to date; {len(entries)} prompts)"
            )
    return 0
