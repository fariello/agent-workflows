def _dirs(args: argparse.Namespace) -> Tuple[Path, Path]:
    from agent_workflows.project_context import resolve_verb_repo_root

    repo_root = resolve_verb_repo_root(getattr(args, "dir", None))
    from agent_workflows.record_producers import resolve_record_path

    try:
        plans_dir = resolve_record_path("plans", target_repo=str(repo_root))
    except Exception:
        plans_dir = repo_root / ".aw" / "records" / "plans"
    if not plans_dir.is_dir() and (repo_root / ".agents" / "plans").is_dir():
        plans_dir = repo_root / ".agents" / "plans"
    elif not plans_dir.is_dir() and (repo_root / ".aw" / "records" / "plans").is_dir():
        plans_dir = repo_root / ".aw" / "records" / "plans"
    return repo_root, plans_dir


def run_index(args: argparse.Namespace) -> int:
    repo_root, plans_dir = _dirs(args)
    limit = getattr(args, "limit", None) or DEFAULT_INDEX_LIMIT
    if getattr(args, "check", False):
        drift = check_drift(repo_root, plans_dir, limit=limit)
        if getattr(args, "agent", False):
            print(_core.render_agent_drift(drift), end="")
            return _core.drift_exit_code(drift)
        if not drift:
            print("plans index --check: clean")
            return 0
        for d in drift:
            print(f"{d.location}: {d.rule}: {d.detail}")
        return 1
    entries, drift = scan_plans(plans_dir)
    plans_dir.mkdir(parents=True, exist_ok=True)
    (plans_dir / INDEX_JSON).write_text(build_index_json(entries), encoding="utf-8")
    (plans_dir / INDEX_MD).write_text(
        build_index_md(entries, limit=limit), encoding="utf-8"
    )
    # Regeneration always writes the CURRENT state (a snapshot); metadata drift (e.g. a plan still
    # lacking an Id) is reported but does NOT block the write. Use `--check` as the gate.
    if drift and not getattr(args, "quiet", False):
        for d in drift:
            print(f"{d.location}: {d.rule}: {d.detail}")
    if not getattr(args, "quiet", False):
        print(f"wrote {INDEX_JSON} + {INDEX_MD} ({len(entries)} plans)")
    return 0


def run_find(args: argparse.Namespace) -> int:
    repo_root, plans_dir = _dirs(args)
    entries, _drift = scan_plans(plans_dir)
    results = query(
        entries,
        plan_id=getattr(args, "id", None),
        set_id=getattr(args, "set", None),
        status=getattr(args, "status", None),
        disposition=getattr(args, "disposition", None),
    )
    if not results:
        from agent_workflows.term import Term
        from agent_workflows.result_types import NextAction

        filters_dict = {}
        for k in ("id", "set", "status", "disposition"):
            v = getattr(args, k, None)
            if v:
                filters_dict[k] = v
        Term().empty_result(
            summary="no matching plans",
            filters=filters_dict if filters_dict else None,
            next_action=NextAction(
                command="aw find plans", description="find across all plans"
            )
            if filters_dict
            else NextAction(
                command="aw ipd scaffold", description="scaffold a new plan"
            ),
        )
        return 0
    for e in results:
        print(f"{e.plan_id or '??????'}\t{e.disposition}\t{e.set_id or '-'}\t{e.path}")
    return 0
