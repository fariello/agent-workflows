def _dirs(args: argparse.Namespace) -> Tuple[Path, Path]:
    from agent_workflows.project_context import (
        resolve_verb_repo_root,
        project_records_dir,
        has_stored_records_placement,
    )

    repo_root = resolve_verb_repo_root(getattr(args, "dir", None))
    from agent_workflows.record_producers import resolve_record_path

    modern_plans = project_records_dir(repo_root) / "plans"
    if has_stored_records_placement(repo_root):
        plans_dir = modern_plans
    else:
        try:
            plans_dir = resolve_record_path("plans", target_repo=str(repo_root))
        except Exception:
            plans_dir = modern_plans
    if not plans_dir.is_dir() and (repo_root / ".agents" / "plans").is_dir():
        plans_dir = repo_root / ".agents" / "plans"
    elif not plans_dir.is_dir() and modern_plans.is_dir():
        plans_dir = modern_plans
    return repo_root, plans_dir


def run_index(args: argparse.Namespace) -> int:
    repo_root, plans_dir = _dirs(args)
    limit = getattr(args, "limit", None) or DEFAULT_INDEX_LIMIT
    if getattr(args, "check", False):
        drift = check_drift(repo_root, plans_dir, limit=limit)
        # tsvagent Order 01 (n9ua3b) E-02: route all audiences through the shared renderer
        # via artifact_core.emit_index_check_result, preserving the legacy human lines byte-exact
        # via data["human_rendered"]. Rely on the renderer's return value (result.exit_code),
        # which identically preserves artifact_core.drift_exit_code(drift).
        return _core.emit_index_check_result(
            args,
            repo_root,
            drift,
            "plans index --check: clean",
            command="index",
            target="plans",
        )
    if not plans_dir.is_dir():
        return _core.emit_index_missing_dir_refusal(
            args, repo_root, plans_dir, target="plans"
        )
    entries, drift = scan_plans(plans_dir)
    json_path = plans_dir / INDEX_JSON
    md_path = plans_dir / INDEX_MD
    new_json = build_index_json(entries)
    new_md = build_index_md(entries, limit=limit)

    json_existed = json_path.exists()
    md_existed = md_path.exists()
    json_changed = (not json_existed) or (
        json_path.read_text(encoding="utf-8") != new_json
    )
    md_changed = (not md_existed) or (md_path.read_text(encoding="utf-8") != new_md)

    if json_changed:
        json_path.write_text(new_json, encoding="utf-8")
    if md_changed:
        md_path.write_text(new_md, encoding="utf-8")

    from agent_workflows.result_types import select_output

    ctx = select_output(args)
    if (ctx.is_agent or ctx.is_json) and not getattr(args, "quiet", False):
        return _core.emit_index_write_result(
            args,
            repo_root,
            plans_dir,
            target="plans",
            noun="plans",
            count=len(entries),
            json_changed=json_changed,
            md_changed=md_changed,
            json_existed=json_existed,
            md_existed=md_existed,
            drift=drift,
        )

    # Regeneration always writes the CURRENT state (a snapshot); metadata drift (e.g. a plan still
    # lacking an Id) is reported but does NOT block the write. Use `--check` as the gate.
    if drift and not getattr(args, "quiet", False):
        for d in drift:
            print(f"{d.location}: {d.rule}: {d.detail}")
    if not getattr(args, "quiet", False):
        # THE OUTCOME WORDS BELOW ARE NOT LIFECYCLE STATUSES, and this module is deliberately NOT
        # converted to the shared lifecycle resolver (plan `9zvl2w` E-01, spec `uonrjg` R10.3).
        # Measured 2026-09-20: all four `status_256` calls in this function render `up to date`,
        # `wrote` or `updated`, each of which greps to ZERO in spec `uonrjg`. They are exactly the
        # "command-level OK, WARN, and FAIL" class R10.3 keeps valid and OUTSIDE that spec, with its
        # explicit warning not to "mechanically replace every checkmark". Routing them through
        # `resolve_lifecycle` would send each to criterion A20's UNKNOWN path and print `?` where a
        # user reads `up to date`: a regression delivered as compliance.
        #
        # AND THIS MODULE HAS NO LIFECYCLE TERMINAL VIEW TO CONVERT. A plan's status does appear in
        # `INDEX.md`, but that is a COMMITTED markdown file (`generated by aw index plans; do not
        # edit by hand`), not human terminal output, and Section 9.5 plus criterion A14 keep
        # committed and machine artifacts ANSI-free. R10.3's "plan index" obligation is satisfied
        # for this module by the plan statuses that reach a human through `aw find`, `aw ipd lint`,
        # `aw set` and `aw attention`, every one of which IS converted.
        #
        # WHAT WAS ACTUALLY WRONG HERE WAS THE COLOR DECISION, not the palette (criteria A14/A11).
        # `Term(color=not no_color)` FORCED color on for every caller that did not pass
        # `--no-color`, bypassing `should_color` entirely, so this line emitted ANSI under `--agent`,
        # under `--json`, under `NO_COLOR=1`, under `TERM=dumb` and into a pipe (all five measured
        # 2026-09-20; `aw find --agent` and `aw ipd lint --agent` emitted zero by contrast). The fix
        # is `color=False if no_color else None`, the package-standard idiom, which defers to the ONE
        # precedence chain in `term.should_color` (flag beats env beats detection), plus the explicit
        # machine-mode suppression below. The WORDS and their palette indices are unchanged.
        from agent_workflows.result_types import select_output
        from agent_workflows.term import Term

        # MACHINE MODE FORCES COLOR OFF, read through the shared output contract rather than by
        # re-testing the flags here, so this command cannot disagree with every other command about
        # what `--agent` means. `select_output` already resolves `color=False` for both AGENT and
        # JSON modes and applies `should_color` for human output.
        try:
            _ctx = select_output(args)
            _color = _ctx.color
        except Exception:
            # A conflicting-flag pair is the caller's error to report, not this print path's; fall
            # back to the ordinary human decision rather than crashing a successful regeneration.
            _color = None if not getattr(args, "no_color", False) else False
        term = Term(color=_color)
        try:
            rel_dir = plans_dir.relative_to(repo_root).as_posix()
        except ValueError:
            rel_dir = plans_dir.as_posix()
        dir_prefix = f"{rel_dir}/" if rel_dir and not rel_dir.endswith("/") else rel_dir
        dir_styled = term.color256(dir_prefix, 33)

        if not json_changed and not md_changed:
            status_lbl = term.status_256("up to date", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}, {INDEX_MD}"
            term.line(f"{status_lbl} {files_str} ({len(entries)} plans)")
        elif json_changed and md_changed:
            status_lbl = term.status_256("wrote", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}, {INDEX_MD}"
            term.line(f"{status_lbl} {files_str} ({len(entries)} plans)")
        elif md_changed:
            status_lbl = term.status_256("updated", width=12)
            files_str = f"{dir_styled}{INDEX_MD}"
            term.line(
                f"{status_lbl} {files_str} ({INDEX_JSON} up to date; {len(entries)} plans)"
            )
        else:
            status_lbl = term.status_256("updated", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}"
            term.line(
                f"{status_lbl} {files_str} ({INDEX_MD} up to date; {len(entries)} plans)"
            )
    return 0


def run_find(args: argparse.Namespace) -> int:
    repo_root, plans_dir = _dirs(args)
    entries, _drift = scan_plans(plans_dir)
    results = query(
        entries,
        plan_id=getattr(args, "id", None),
        set_id=getattr(args, "set", None),
        status=getattr(args, "status", None),
        disposition=getattr(args, "disposition", None),
        status_not=getattr(args, "status_not", None),
    )
    if not results:
        from agent_workflows.result_types import NextAction
        from agent_workflows.term import Term

        filters_dict = {}
        for k in ("id", "set", "status", "status_not", "disposition"):
            v = getattr(args, k, None)
            if v:
                filters_dict[k] = v
        Term().empty_result(
            summary="no matching plans",
            filters=filters_dict if filters_dict else None,
            next_action=NextAction(
                command="aw find plans", description="find across all plans"
            )
            if filters_dict
            else NextAction(
                command="aw ipd scaffold", description="scaffold a new plan"
            ),
        )
        return 0
    for e in results:
        print(f"{e.plan_id or '??????'}\t{e.disposition}\t{e.set_id or '-'}\t{e.path}")
    return 0
