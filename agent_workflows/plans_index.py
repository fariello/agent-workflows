"""Plans tiered manifest + browse-by-Set + drift check (Set plans-adopter, Order 03).

``aw plans index [--check]`` regenerates ``.agents/plans/INDEX.json`` (every plan, all fields) and a
browse-by-``Set:`` human view (``INDEX.md``: each Set lists its members in ``Order``, Sets ordered by
most-recent activity, bounded to the 40 most-recent Sets, the rest available in the JSON). ``aw plans
find`` queries the manifest. ``--check`` fails on the four drift classes (missing/invalid ``Id``,
name-vs-metadata mismatch on a clustered name, stale generated view, dangling plan citation).

Consumes the shared core (Order 01: id6, Drift shape, dangling detector) and the required plan
``Id`` (Order 02). The scan is RECURSIVE so plans that Order 05 moves into
``<disposition>/YYYYMM/`` shards remain visible; disposition is the TOP-LEVEL directory even
when a plan sits in a shard subdir. Complements (does not replace) the disposition-grouped
``STATUS.md`` from ``plans.py``.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Dict, List, NamedTuple, Optional, Tuple

from agent_workflows import artifact_core as _core

DEFAULT_INDEX_LIMIT = 40  # OQ5: browse-by-Set view bounded to the N most-recent Sets.
# (The former module-level `PLANS_DIR = ".agents/plans"` was dead - resolution is via `_dirs()` /
# `resolve_record_path` - and was removed in Order 05, S5-DC01.)
INDEX_JSON = "INDEX.json"
INDEX_MD = "INDEX.md"
_MD_HEADER = "<!-- generated by `aw index plans`; do not edit by hand -->"

_META_RE = {
    "Date": re.compile(r"(?m)^- Date:\s*(.+?)\s*$"),
    "Kind": re.compile(r"(?m)^- Kind:\s*(.+?)\s*$"),
    "Status": re.compile(r"(?m)^- Status:\s*(.+?)\s*$"),
    "Id": re.compile(r"(?m)^- Id:\s*([0-9a-z]{6})\s*$"),
    "Set": re.compile(r"(?m)^- Set:\s*(.+?)\s*$"),
    "Order": re.compile(r"(?m)^- Order:\s*(\d+)\s*$"),
}

_EXCLUDE_NAMES = {"INDEX.json", "INDEX.md", "STATUS.md", "README.md"}


class PlanEntry(NamedTuple):
    """One indexed plan (derived from its disposition dir + metadata)."""

    plan_id: Optional[str]
    path: str  # posix, relative to the plans dir
    disposition: (
        str  # top-level dir (pending/executed/superseded/not-executed/reusable)
    )
    date: str
    set_id: Optional[str]
    order: Optional[int]
    status: Optional[str]
    kind: Optional[str]


def _meta(text: str, key: str) -> Optional[str]:
    m = _META_RE[key].search(text)
    return m.group(1) if m else None


def set_terse_id(raw: Optional[str]) -> Optional[str]:
    """Extract the canonical terse set-id from a `Set:` value of the form ``<terse> (<descriptive>)``.

    The leading whitespace-delimited token before any ``(`` is the set-id; the parenthetical is a
    human-readable display name (plans-adopter Order 06). A bare terse id (no parenthetical) also
    parses. Returns None for None.
    """

    if raw is None:
        return None
    return raw.split("(", 1)[0].strip() or None


def scan_plans(plans_dir: Path) -> Tuple[List[PlanEntry], List[_core.Drift]]:
    """Recursively scan every plan under ``plans_dir``; return (entries, drift).

    Disposition is the first path component under ``plans_dir`` (so a plan inside a
    ``<disposition>/YYYYMM/`` shard keeps its top-level disposition). Drift here covers the
    metadata classes (missing/invalid Id); name-vs-metadata and stale-view/dangling are added by
    ``check_drift``.
    """

    entries: List[PlanEntry] = []
    drift: List[_core.Drift] = []
    if not plans_dir.is_dir():
        return entries, drift
    for p in sorted(plans_dir.rglob("*.md")):
        if p.name in _EXCLUDE_NAMES:
            continue
        rel = p.relative_to(plans_dir).as_posix()
        disposition = rel.split("/", 1)[0]
        text = p.read_text(encoding="utf-8")
        plan_id = _meta(text, "Id")
        order_raw = _meta(text, "Order")
        entries.append(
            PlanEntry(
                plan_id=plan_id,
                path=rel,
                disposition=disposition,
                date=str(_meta(text, "Date") or ""),
                set_id=set_terse_id(_meta(text, "Set")),
                order=int(order_raw) if order_raw else None,
                status=_meta(text, "Status"),
                kind=_meta(text, "Kind"),
            )
        )
        # Drift class (a): missing/invalid Id. Terminal grandfathered plans are still expected to
        # carry an Id after migration; report a missing/invalid one regardless of disposition.
        if plan_id is None:
            drift.append(_core.Drift(rel, "id-missing", "no `- Id:` metadata line"))
        elif not _core.is_valid_id6(plan_id):
            drift.append(
                _core.Drift(
                    rel, "id-invalid", f"Id '{plan_id}' is not a 6-char base36 token"
                )
            )
    return entries, drift


def build_index_json(entries: List[PlanEntry]) -> str:
    """Render the complete plans manifest as deterministic JSON (sorted by path)."""

    payload = [e._asdict() for e in sorted(entries, key=lambda e: e.path)]
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def _set_last_touched(entries: List[PlanEntry]) -> Dict[str, str]:
    lt: Dict[str, str] = {}
    for e in entries:
        key = e.set_id or f"(singleton) {e.path}"
        if key not in lt or e.date > lt[key]:
            lt[key] = e.date
    return lt


def build_index_md(entries: List[PlanEntry], limit: int = DEFAULT_INDEX_LIMIT) -> str:
    """Render the browse-by-Set view: group by Set, members in Order, Sets by recent activity,
    bounded to the N most-recent Sets; Set-less plans in a singleton band."""

    last_touched = _set_last_touched(entries)
    # Group by Set (Set-less -> the singleton band, keyed by None).
    by_set: Dict[Optional[str], List[PlanEntry]] = {}
    for e in entries:
        by_set.setdefault(e.set_id, []).append(e)

    real_sets = [s for s in by_set if s is not None]

    def _inv_date(d: str) -> str:
        return "".join(str(9 - int(c)) if c.isdigit() else c for c in d) if d else ""

    # Sets ordered by most-recent activity (desc), tie-broken by set-id asc.
    ordered_sets = sorted(
        real_sets, key=lambda s: (_inv_date(last_touched.get(s, "")), s)
    )
    shown = ordered_sets[:limit]

    lines = [_MD_HEADER, "", "# Plans by topic (Set)", ""]
    lines.append(
        f"Showing the {len(shown)} most-recent of {len(real_sets)} Sets; the full manifest is INDEX.json."
    )
    lines.append("")
    for s in shown:
        members = sorted(
            by_set[s], key=lambda e: (e.order if e.order is not None else 0, e.path)
        )
        lines.append(f"## {s}")
        lines.append("")
        for e in members:
            oid = f"{e.order:02d}" if e.order is not None else "--"
            pid = e.plan_id or "??????"
            lines.append(f"- `{pid}` [{e.disposition}] {oid} {e.path}")
        lines.append("")
    singletons = by_set.get(None, [])
    if singletons:
        lines.append("## (singletons: no Set)")
        lines.append("")
        for e in sorted(singletons, key=lambda e: e.path):
            pid = e.plan_id or "??????"
            lines.append(f"- `{pid}` [{e.disposition}] {e.path}")
        lines.append("")
    return "\n".join(lines)


