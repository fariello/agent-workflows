def _roots(args: argparse.Namespace) -> Tuple[Path, Path]:
    from agent_workflows.project_context import resolve_verb_repo_root

    repo_root = resolve_verb_repo_root(getattr(args, "dir", None))
    from agent_workflows.record_producers import resolve_record_path

    try:
        res_root = resolve_record_path("research", target_repo=str(repo_root))
    except Exception:
        res_root = repo_root / ".aw" / "records" / "research"
    if not res_root.is_dir() and (repo_root / ".agents" / "docs" / "research").is_dir():
        res_root = repo_root / ".agents" / "docs" / "research"
    elif (
        not res_root.is_dir() and (repo_root / ".aw" / "records" / "research").is_dir()
    ):
        res_root = repo_root / ".aw" / "records" / "research"
    return repo_root, res_root


def run_index(args: argparse.Namespace) -> int:
    repo_root, research_root = _roots(args)
    limit = getattr(args, "limit", None) or DEFAULT_INDEX_LIMIT
    if getattr(args, "check", False):
        drift = check_drift(repo_root, research_root, limit=limit)
        if getattr(args, "agent", False):
            for d in drift:
                print(f"{d.location}\t{d.rule}\t{d.detail}")
            return 1 if drift else 0
        if not drift:
            print("index --check: clean")
            return 0
        for d in drift:
            print(f"{d.location}: {d.rule}: {d.detail}")
        return 1
    # Regenerate.
    entries, drift = _scan_docs(research_root)
    if drift:
        # Refuse to write over invalid input; report and exit nonzero.
        if not getattr(args, "quiet", False):
            for d in drift:
                print(f"{d.location}: {d.rule}: {d.detail}")
        return 1
    json_path = research_root / INDEX_JSON
    md_path = research_root / INDEX_MD
    new_json = build_index_json(entries)
    new_md = build_index_md(entries, limit=limit)

    json_changed = (not json_path.exists()) or (
        json_path.read_text(encoding="utf-8") != new_json
    )
    md_changed = (not md_path.exists()) or (
        md_path.read_text(encoding="utf-8") != new_md
    )

    if json_changed:
        json_path.write_text(new_json, encoding="utf-8")
    if md_changed:
        md_path.write_text(new_md, encoding="utf-8")

    if not getattr(args, "quiet", False):
        from agent_workflows.term import Term

        term = Term(color=not getattr(args, "no_color", False))
        try:
            rel_dir = research_root.relative_to(repo_root).as_posix()
        except ValueError:
            rel_dir = research_root.as_posix()
        dir_prefix = f"{rel_dir}/" if rel_dir and not rel_dir.endswith("/") else rel_dir
        dir_styled = term.color256(dir_prefix, 33)

        if not json_changed and not md_changed:
            status_lbl = term.status_256("up to date", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}, {INDEX_MD}"
            term.line(f"{status_lbl} {files_str} ({len(entries)} docs)")
        elif json_changed and md_changed:
            status_lbl = term.status_256("wrote", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}, {INDEX_MD}"
            term.line(f"{status_lbl} {files_str} ({len(entries)} docs)")
        elif md_changed:
            status_lbl = term.status_256("updated", width=12)
            files_str = f"{dir_styled}{INDEX_MD}"
            term.line(
                f"{status_lbl} {files_str} ({INDEX_JSON} up to date; {len(entries)} docs)"
            )
        else:
            status_lbl = term.status_256("updated", width=12)
            files_str = f"{dir_styled}{INDEX_JSON}"
            term.line(
                f"{status_lbl} {files_str} ({INDEX_MD} up to date; {len(entries)} docs)"
            )
    return 0


def run_find(args: argparse.Namespace) -> int:
    repo_root, research_root = _roots(args)
    entries, _drift = _scan_docs(research_root)
    results = query(
        entries,
        id6=getattr(args, "id", None),
        set_id=getattr(args, "set", None),
        topic=getattr(args, "topic", None),
        status=getattr(args, "status", None),
    )
    if not results:
        from agent_workflows.term import Term
        from agent_workflows.result_types import NextAction

        filters_dict = {}
        for k in ("id", "set", "topic", "status"):
            v = getattr(args, k, None)
            if v:
                filters_dict[k] = v
        Term().empty_result(
            summary="no matching research docs",
            filters=filters_dict if filters_dict else None,
            next_action=NextAction(
                command="aw research find", description="find across all research docs"
            )
            if filters_dict
            else NextAction(
                command="aw research new", description="create a new research doc"
            ),
        )
        return 0
    for e in results:
        print(f"{e.id6}\t{e.status}\t{e.path}\t{e.summary}")
    return 0
