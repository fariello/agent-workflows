def test_headless_noninteractive_run_stops_at_needs_input_before_side_effect(
    deploy_gate: run_gates.DecisionGate,
    sample_action: Callable[[], str],
    side_effects: list[int],
) -> None:
    """Headless run (interactive=False) MUST stop at needs_input and never execute side effect."""
    decision, result = run_gates.execute_gated_action(
        gate=deploy_gate,
        action=sample_action,
        interactive=False,
    )
    assert decision.status == run_gates.GATE_STATUS_NEEDS_INPUT
    assert decision.selected_option is None
    assert decision.approver is None
    assert decision.interactive is False
    assert result is None
    assert side_effects == []


def test_no_synthesized_consent_even_if_default_is_approve() -> None:
    """Consent must NEVER be synthesized: even if default_option='approve', headless returns needs_input."""
    dangerous_gate = run_gates.DecisionGate(
        gate_id="dangerous_gate",
        prompt="Proceed with irreversible wipe?",
        options=("approve", "cancel"),
        default_option="approve",
        timeout_policy="apply_default",
        requires_human=True,
    )
    decision = run_gates.evaluate_gate(dangerous_gate, interactive=False)
    assert decision.status == run_gates.GATE_STATUS_NEEDS_INPUT
    assert decision.is_approved is False


