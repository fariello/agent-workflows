def test_stdin_fallback_empty_reply_with_default_abort(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Empty stdin response applies declared default and renders prompt with gate id, options, and default."""
    captured: list[str] = []
    monkeypatch.setattr("builtins.input", lambda prompt: captured.append(prompt) or "")
    gate = run_gates.DecisionGate(
        gate_id="deploy_approval_gate",
        prompt="Authorize deploy?",
        options=("approve", "reject", "abort"),
        default_option="abort",
    )
    decision = run_gates.evaluate_gate(gate, interactive=True)
    assert decision.status == run_gates.GATE_STATUS_ABORTED
    assert decision.selected_option == "abort"
    assert len(captured) == 1
    prompt = captured[0]
    assert "deploy_approval_gate" in prompt
    assert "approve/reject/abort" in prompt
    assert "[abort]" in prompt


