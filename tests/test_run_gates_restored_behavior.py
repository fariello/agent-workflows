def test_gate_integration_with_run_engine_and_ledger(
    tmp_path: Path,
    deploy_gate: run_gates.DecisionGate,
    sample_action: Callable[[], str],
    side_effects: list[int],
) -> None:
    """Approved execute_gated_action unblocks engine step and records human_approval in ledger."""
    lpath = tmp_path / "run.jsonl"
    store = run_ledger_store.RunLedgerStore(lpath)
    store.append(
        {
            "schema_version": run_ledger_schema.LEDGER_SCHEMA_VERSION,
            "kind": "run",
            "run_id": "run-00000001",
            "actor": "runtime",
            "workflow_digest": "a" * 64,
            "requirement_digest": "b" * 64,
            "repo": "test-repo",
            "head": "c" * 64,
            "parent": "",
        }
    )
    store.append(
        {
            "schema_version": run_ledger_schema.LEDGER_SCHEMA_VERSION,
            "kind": "requirement_set",
            "run_id": "run-00000001",
            "actor": "runtime",
            "requirement_digest": "b" * 64,
            "requirements": [{"id": "R-01"}],
            "scope_fence": {},
            "parent": "",
        }
    )
    wf = {
        "id": "gated-wf",
        "steps": [
            {
                "id": "S-01",
                "action": "gated deploy",
                "gates": ["deploy_approval_gate"],
                "satisfies": ["R-01"],
            }
        ],
        "requirements": [{"id": "R-01"}],
    }
    engine = run_engine.RunEngine(wf, store, run_id="run-00000001")
    assert engine.get_runnable_steps() == []

    decision, result = run_gates.execute_gated_action(
        gate=deploy_gate,
        action=sample_action,
        engine=engine,
        interactive=True,
        input_handler=lambda _g: "approve",
        approver="carol-lead",
    )
    assert decision.is_approved is True
    assert result == "DEPLOYMENT_SUCCESS"
    assert side_effects == [1]
    runnable = engine.get_runnable_steps()
    assert [s.step_id for s in runnable] == ["S-01"]
    records = store.read_records(verify=True)
    app_recs = [r for r in records if r.get("kind") == "human_approval"]
    assert len(app_recs) == 1
    assert app_recs[0]["gate"] == "deploy_approval_gate"
    assert app_recs[0]["approver"] == "carol-lead"
    assert app_recs[0]["actor"] == "human"


